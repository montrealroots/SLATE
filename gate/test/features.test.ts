import { describe, expect, it } from 'vitest';
import { checkFeatures, scanAnchors, scanFeatureMarks, type FalsifierRecord } from '../checks/features.ts';
import { all, fixture } from './fixture.ts';

const F = 'registry/features.json';
const pages = { 'creation.background': { title: 'Background', decidedIn: 'docs/KEEP.md entry 9' } };
const ID = 'background.family-means';
const features = { [ID]: { page: 'creation.background', kind: 'field', what: "The family's means" } };
const PAGE = 'src/ui/creation/Family.tsx';
const ENGINE = 'src/person/family/family.ts';
const page = `export function Family() {
  // @slate:reads ${ID}
  const means = useLife().family.means;
  return <select data-feature="${ID}" value={means} onChange={choose} />;
}
`;
const engine = `export function choose(life, means) {
  // @slate:bites ${ID}
  life.family.means = means;
}
export function firstMorning(life) {
  /* @slate:downstream ${ID} */
  return startingMoney(life.family.means);
}
`;
const T = 'tests/person/family.test.ts';
const proofs: FalsifierRecord[] = [
  { feature: ID, claim: 'downstream', file: T, test: 'family > the means set the first morning' },
  { feature: ID, claim: 'bites', file: T, test: 'family > choosing changes the means' },
];
const passed = new Set(proofs.map((p) => `${p.file}::${p.test}`));
const repo = (over: Record<string, unknown> = {}) => fixture({ 'registry/pages.json': pages, [F]: features, [PAGE]: page, [ENGINE]: engine, ...over }).repo;
const findings = (over: Record<string, unknown> = {}, p: FalsifierRecord[] = proofs, ok: ReadonlySet<string> = passed) => all(checkFeatures(repo(over), p, { passed: ok }));

describe('anchors', () => {
  it('bind to the next line of code, past blank lines and every kind of comment', () => {
    const text = '// @slate:reads a.b\n\n// more\n * still comment\n/* block */\n{/* jsx */}\n{ /* jsx, spaced */ }\n   \nconst x = 1;\n';
    expect(scanAnchors('f.ts', text)).toEqual({ anchors: [{ claim: 'reads', feature: 'a.b', file: 'f.ts', line: 9 }], errors: [] });
  });
  it('take any run of spaces before the feature', () => {
    expect(scanAnchors('f.ts', '// @slate:reads   a.b\nx();\n')).toEqual({ anchors: [{ claim: 'reads', feature: 'a.b', file: 'f.ts', line: 2 }], errors: [] });
  });
  it('bind to a line of code that ends in a comment', () => {
    expect(scanAnchors('f.ts', '// @slate:reads a.b\nrun(); // why\n').anchors[0]?.line).toBe(2);
  });
  it('bind to their own line when code comes before them', () => {
    expect(scanAnchors('f.ts', 'x = 1; // @slate:bites a.b\n').anchors[0]?.line).toBe(1);
    expect(scanAnchors('f.ts', 'x=1;// @slate:bites a.b\ny();\n').anchors[0]?.line).toBe(1);
    expect(scanAnchors('f.ts', 'f(/* @slate:bites a.b */);\ny();\n').anchors[0]?.line).toBe(1);
  });
  it('bind past a JSX comment and an indented block comment', () => {
    expect(scanAnchors('f.tsx', '  {/* @slate:reads a.b */}\n<p>{x}</p>\n').anchors[0]?.line).toBe(2);
    expect(scanAnchors('f.tsx', '  /* @slate:reads a.b */\n  go();\n').anchors[0]?.line).toBe(2);
  });
  it('bind several on one line, each to the same code', () => {
    expect(scanAnchors('f.ts', '// @slate:reads a.b @slate:bites a.c\ny();\n').anchors).toEqual([
      { claim: 'reads', feature: 'a.b', file: 'f.ts', line: 2 },
      { claim: 'bites', feature: 'a.c', file: 'f.ts', line: 2 },
    ]);
  });
  it('fail with no code under them, or malformed, at their own line', () => {
    expect(scanAnchors('f.ts', 'x();\n// @slate:reads a.b\n\n// end\n')).toEqual({ anchors: [], errors: [{ line: 2, message: 'an anchor with no code under it' }] });
    const malformed = 'a malformed @slate anchor (it is @slate:reads|bites|downstream <feature-id>)';
    expect(scanAnchors('f.ts', 'x();\n// @slate:affects a.b\nx();\n').errors).toEqual([{ line: 2, message: malformed }]);
    expect(scanAnchors('f.ts', '// @slate:reads\nx();\n').errors).toEqual([{ line: 1, message: malformed }]);
  });
});

describe('feature marks', () => {
  it('are found in every quoting, spaced or not', () => {
    expect(scanFeatureMarks(`<a data-feature="x.y" /><b data-feature='x.z' /><c data-feature={'x.w'} /><d data-feature={ "x.v" } /><e data-feature={ns} />`)).toEqual(['x.y', 'x.z', 'x.w', 'x.v']);
  });
});

describe('the feature-matrix check', () => {
  it('passes a feature that is on a page, reads, bites, is read downstream, and is falsified twice, and writes the matrix', () => {
    const r = checkFeatures(repo(), proofs, { passed });
    expect(all(r)).toEqual([]);
    expect(r.check).toBe('feature-matrix');
    expect(r.notes).toEqual(['1 features, 3 anchors, 2 falsifiers accepted']);
    expect(r.generated).toEqual([
      {
        path: 'matrix/FEATURES.md',
        content: [
          '# The Feature-To-Effect Matrix',
          '',
          'Generated by the gate from `registry/features.json`, the `@slate:` anchors in `src/`, and the falsifiers recorded',
          'by the last test run; do not edit by hand. Every feature reads, bites, and is read downstream, each at a file and',
          'line, and a passing test shows that changing its input changes the outcome.',
          '',
          'Features: 1.',
          '',
          '| Feature | Reads | Bites | Downstream | Falsified by |',
          '|---|---|---|---|---|',
          `| \`${ID}\` | \`${PAGE}:3\` | \`${ENGINE}:3\` | \`${ENGINE}:7\` | bites: ${T} › family > choosing changes the means<br>downstream: ${T} › family > the means set the first morning |`,
          '',
        ].join('\n'),
      },
    ]);
  });
  it('lists several anchors and proofs of one claim, in order, and marks what is missing', () => {
    const second = `export const again = (l) => {\n  // @slate:bites ${ID}\n  l.x = 1;\n};\n`;
    const more = [...proofs, { feature: ID, claim: 'bites', file: T, test: 'family > also' }];
    const r = checkFeatures(repo({ 'src/person/family/again.ts': second }), more, { passed: new Set([...passed, `${T}::family > also`]) });
    expect(r.generated[0]?.content).toContain(`| \`src/person/family/again.ts:3\`<br>\`${ENGINE}:3\` |`);
    expect(r.generated[0]?.content).toContain(`bites: ${T} › family > also<br>bites: ${T} › family > choosing changes the means<br>downstream:`);
    const bare = checkFeatures(repo({ [ENGINE]: 'export {};\n' }), [], { passed });
    expect(bare.generated[0]?.content).toContain(`| \`${ID}\` | \`${PAGE}:3\` | **missing** | **missing** | bites: **missing**<br>downstream: **missing** |`);
  });
  it('lists the proofs sorted by file and test, whatever order the ledger gave them', () => {
    const p = (file: string, test: string): FalsifierRecord => ({ feature: ID, claim: 'bites', file, test });
    const names = ['k', 'c', 'x', 'a', 'q', 'e', 'z', 'b', 'm', 'h', 'w', 'd'];
    const given = [...names.map((t, i) => p(`tests/${i % 2 === 0 ? 'b' : 'a'}.test.ts`, t)), proofs[0] as FalsifierRecord];
    const r = checkFeatures(repo(), given, { passed: new Set(given.map((x) => `${x.file}::${x.test}`)) });
    const want = [...given.slice(0, -1)].map((x) => `${x.file} › ${x.test}`).sort().map((x) => `bites: ${x}`).join('<br>');
    expect(r.generated[0]?.content).toContain(`${want}<br>downstream:`);
  });
  it('fails a feature on no page', () => {
    expect(findings({ [PAGE]: page.replace(` data-feature="${ID}"`, '') })).toEqual([`red ${F} ${ID} | the feature is on no page (no element carries its data-feature)`]);
  });
  it('fails a feature missing any of its three anchors', () => {
    expect(findings({ [PAGE]: page.replace(`// @slate:reads ${ID}\n`, '') })).toEqual([`red ${F} ${ID} | the feature has no reads anchor`]);
    expect(findings({ [ENGINE]: engine.replace(`// @slate:bites ${ID}\n`, '') })).toEqual([`red ${F} ${ID} | the feature has no bites anchor`]);
    expect(findings({ [ENGINE]: engine.replace(`/* @slate:downstream ${ID} */\n`, '') })).toEqual([`red ${F} ${ID} | the feature has no downstream anchor`]);
  });
  it("counts only a feature's own anchors", () => {
    const other = { 'other.thing': { page: 'creation.background', kind: 'display', what: 'Another' } };
    const r = findings({ [F]: { ...features, ...other }, 'src/ui/creation/Other.tsx': '<p data-feature="other.thing" />\n' });
    expect(r).toEqual([
      `red ${F} other.thing | the feature has no reads anchor`,
      `red ${F} other.thing | the feature has no bites anchor`,
      `red ${F} other.thing | the feature has no downstream anchor`,
      `red ${F} other.thing | no passing test falsifies the bites claim`,
      `red ${F} other.thing | no passing test falsifies the downstream claim`,
    ]);
  });
  it('fails a downstream reader in any file that draws the feature', () => {
    const selfVouching = `${page}// @slate:downstream ${ID}\nexport const again = 1;\n`;
    expect(findings({ [PAGE]: selfVouching, [ENGINE]: engine.replace(`/* @slate:downstream ${ID} */\n`, '') })).toEqual([
      `red ${PAGE}:7 | a downstream reader must sit outside the files that draw the feature`,
      `red ${F} ${ID} | the feature has no downstream anchor`,
    ]);
    const drawnTwice = `<p data-feature="${ID}" />\n// @slate:downstream ${ID}\nexport const z = 1;\n`;
    expect(findings({ 'src/ui/creation/Also.tsx': drawnTwice })).toEqual([`red src/ui/creation/Also.tsx:3 | a downstream reader must sit outside the files that draw the feature`]);
    // Drawn first in Also.tsx, then in Family.tsx, which also claims to read it downstream.
    expect(findings({ 'src/ui/creation/Also.tsx': `<p data-feature="${ID}" />\n`, [PAGE]: selfVouching })).toEqual([`red ${PAGE}:7 | a downstream reader must sit outside the files that draw the feature`]);
  });
  it('fails a claim no passing test falsifies, and accepts no other feature\'s proof', () => {
    expect(findings({}, proofs.filter((p) => p.claim === 'bites'))).toEqual([`red ${F} ${ID} | no passing test falsifies the downstream claim`]);
    expect(findings({}, proofs, new Set([`${T}::family > choosing changes the means`]))).toEqual([`red ${F} ${ID} | no passing test falsifies the downstream claim`]);
    const others = { 'other.thing': { page: 'creation.background', kind: 'display', what: 'x' } };
    const r = findings({ [F]: { ...features, ...others }, 'src/ui/creation/Other.tsx': '<p data-feature="other.thing" />\n// @slate:reads other.thing\nx();\n// @slate:bites other.thing\ny();\n', 'src/core/x/x.ts': '// @slate:downstream other.thing\nz();\n' });
    expect(r).toEqual([`red ${F} other.thing | no passing test falsifies the bites claim`, `red ${F} other.thing | no passing test falsifies the downstream claim`]);
  });
  it('fails a name that is not a registered feature, wherever it appears', () => {
    expect(findings({ 'src/ui/creation/Other.tsx': '// @slate:reads ghost.feature\nx();\n<p data-feature="ghost.other" />\n' }, [...proofs, { feature: 'ghost.proof', claim: 'bites', file: T, test: 't' }])).toEqual([
      'red src/ui/creation/Other.tsx | data-feature names "ghost.other", which isn\'t a registered feature',
      'red src/ui/creation/Other.tsx:2 | an anchor names "ghost.feature", which isn\'t a registered feature',
      `red ${T} | a falsifier names "ghost.proof", which isn't a registered feature`,
    ]);
  });
  it('does not count anchors or marks in tests', () => {
    expect(findings({ [ENGINE]: 'export {};\n', 'src/person/family/family.test.ts': engine })).toEqual([`red ${F} ${ID} | the feature has no bites anchor`, `red ${F} ${ID} | the feature has no downstream anchor`]);
  });
  it('fails a malformed anchor in the source, at its line', () => {
    expect(findings({ 'src/core/x/x.ts': 'y();\n// @slate:uses a.b\nx();\n' })).toEqual(['red src/core/x/x.ts:2 | a malformed @slate anchor (it is @slate:reads|bites|downstream <feature-id>)']);
  });
  it('fails a feature without a well-formed id, a registered page, a known kind, or a description', () => {
    const at = (id: string) => `red ${F} ${id}`;
    const one = (id: string, f: unknown) => findings({ [F]: { [id]: f } }, []).filter((x) => !/anchor|falsif|no page|registered feature/.test(x));
    for (const id of ['Bad.id', 'a.b!', 'abc', 'a', '1a.b']) expect(one(id, features[ID])).toEqual([`${at(id)} | a feature id is dotted lower-case words`]);
    expect(one('a.b.c-d', features[ID])).toEqual([]);
    expect(one('a.b', { ...features[ID], page: 'nowhere' })).toEqual([`${at('a.b')} | a feature's page must be a registered page (nowhere)`]);
    expect(one('a.b', { ...features[ID], page: undefined })).toEqual([`${at('a.b')} | a feature's page must be a registered page (undefined)`]);
    expect(one('a.b', { ...features[ID], kind: 'widget' })).toEqual([`${at('a.b')} | a feature's kind is field, control, display`]);
    expect(one('a.b', { ...features[ID], what: '' })).toEqual([`${at('a.b')} | a feature says what it is`]);
    expect(one('a.b', 'x')).toEqual([`${at('a.b')} | a feature is an object`]);
  });
  it('fails a page without its title or where it was decided', () => {
    for (const bad of [{ title: 'Home' }, { decidedIn: 'x' }, 'x']) {
      expect(findings({ 'registry/pages.json': { ...pages, home: bad } })).toEqual(['red registry/pages.json home | a page needs its "title" and where the owner "decidedIn" it']);
    }
  });
  it('fails a missing or malformed registry', () => {
    const only = (files: Record<string, unknown>) => all(checkFeatures(fixture(files).repo, [], { passed }));
    expect(only({ 'registry/pages.json': pages })).toEqual([`red ${F} | ${F} is missing`]);
    expect(only({ [F]: {} })).toEqual(['red registry/pages.json | registry/pages.json is missing']);
    expect(only({ [F]: [], 'registry/pages.json': {} })).toEqual([`red ${F} | the feature registry is not an object`]);
    expect(only({ [F]: {}, 'registry/pages.json': [] })).toEqual(['red registry/pages.json | the page registry is not an object']);
  });
});
