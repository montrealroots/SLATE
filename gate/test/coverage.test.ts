import { describe, expect, it } from 'vitest';
import { checkCoverage } from '../checks/coverage.ts';
import type { LayerLedger } from '../checks/layers.ts';
import type { RegisterIndex } from '../checks/register.ts';
import { all, fixture } from './fixture.ts';

const ledger: LayerLedger = {
  layers: [
    { n: 0, name: 'Gate', dirs: ['gate'], holdsEngines: false },
    { n: 1, name: 'Core', dirs: ['src/core'], holdsEngines: true },
    { n: 2, name: 'World', dirs: ['src/world', 'src/places'], holdsEngines: true },
    { n: 3, name: 'Screens', dirs: ['src/ui'], holdsEngines: false },
  ],
  proven: [],
};
const E = 'registry/engines.json';
const A = 'registry/axes.json';
const W = 'coverage/weather.json';
const G = 'coverage/gazetteer.json';
const axes = {
  country: { source: 'src/world/gazetteer/countries.json', pick: 'keys', count: 3, decidedIn: 'KEEP 19' },
  place: { source: 'src/world/gazetteer/place-ids.json', pick: 'array', count: 4, decidedIn: 'KEEP 19' },
};
const T = 'tests/world/weather.test.ts::weather > holds';
const ALL = 'tests/world/weather.test.ts::weather > every place';
const register: RegisterIndex = {
  entries: new Map([
    ['R-0001', { id: 'R-0001', fact: 'climate.fr', status: 'found' }],
    ['R-0002', { id: 'R-0002', fact: 'climate.xx', status: 'blocked' }],
    ['R-0003', { id: 'R-0003', fact: 'game.thing', status: 'game' }],
    ['R-0004', { id: 'R-0004', fact: 'climate.de', status: 'secondary' }],
  ]),
};
const rows = [
  { key: 'FR', status: 'researched', register: ['R-0001'], tests: [T] },
  { key: 'DE', status: 'researched', register: ['R-0004'], tests: [T] },
  { key: 'XX', status: 'blocked', register: ['R-0002'], tests: [T] },
];
const weather = { layer: 2, dir: 'src/world/weather', readsPlace: true, matrices: [W], allPlacesTest: ALL };
const gazetteer = { layer: 2, dir: 'src/world/gazetteer', readsPlace: false, matrices: [G] };
const engines = { 'world.weather': weather, 'world.gazetteer': gazetteer };
const files = (over: Record<string, unknown> = {}) => ({
  [A]: axes,
  [E]: engines,
  'src/world/gazetteer/countries.json': { FR: {}, DE: {}, XX: {} },
  'src/world/gazetteer/place-ids.json': ['1', '2', '3', '4'],
  [W]: { engine: 'world.weather', axis: 'country', rows },
  [G]: { engine: 'world.gazetteer', axis: 'place', rows: ['1', '2', '3', '4'].map((key) => ({ key, status: 'proven', tests: [T] })) },
  'src/world/weather/weather.ts': 'export {};\n',
  'src/world/gazetteer/gazetteer.ts': 'export {};\n',
  ...over,
});
const passed = new Set([T, ALL]);
const run = (over: Record<string, unknown> = {}, p: ReadonlySet<string> = passed) => checkCoverage(fixture(files(over)).repo, ledger, register, { passed: p });
const findings = (over: Record<string, unknown> = {}, p?: ReadonlySet<string>) => all(run(over, p));
const weatherRows = (r: unknown[]) => ({ [W]: { engine: 'world.weather', axis: 'country', rows: r } });

describe('the coverage check', () => {
  it('passes engines whose every row is covered, cited and held by a passing test, and writes the summary', () => {
    const r = run();
    expect(all(r)).toEqual([]);
    expect(r.check).toBe('coverage');
    expect(r.notes).toEqual(['2 engines; 0 rows pending']);
    expect(r.generated).toEqual([
      {
        path: 'matrix/COVERAGE.md',
        content: [
          '# Coverage, Engine By Engine',
          '',
          'Generated by the gate from `registry/engines.json` and the matrices it names; do not edit by hand.',
          '',
          '| Engine | Layer | Reads a place | Researched | Proven | Blocked | Game | Pending |',
          '|---|---|---|---|---|---|---|---|',
          '| `world.weather` | 2 | yes | 2 | 0 | 1 | 0 | 0 |',
          '| `world.gazetteer` | 2 | no | 0 | 4 | 0 | 0 | 0 |',
          '',
          '### world.weather: country',
          '',
          '`coverage/weather.json`, 3 keys.',
          '',
          '### world.gazetteer: place',
          '',
          '`coverage/gazetteer.json`, 4 keys.',
          '',
        ].join('\n'),
      },
    ]);
  });
  it('holds a pending row as unfinished, not broken, and counts it', () => {
    const r = run(weatherRows([rows[0], rows[1], { key: 'XX', status: 'pending' }]));
    expect(all(r)).toEqual(['incomplete - | 1 coverage rows are pending']);
    expect(r.notes).toEqual(['2 engines; 1 rows pending']);
    expect(r.generated[0]?.content).toContain('| `world.weather` | 2 | yes | 2 | 0 | 0 | 0 | 1 |');
  });
  it('fails a key of the axis with no row, a row off the axis, and a key twice', () => {
    expect(findings(weatherRows([rows[0], rows[0], { key: 'ZZ', status: 'pending' }]))).toEqual([
      `red ${W} FR | the key has two rows`,
      `red ${W} ZZ | the key isn't in the axis "country"`,
      `red ${W} | 2 keys of the axis "country" have no row (first: DE, XX)`,
      'incomplete - | 1 coverage rows are pending',
    ]);
  });
  it('names at most five of the missing keys', () => {
    const many = Object.fromEntries(['A', 'B', 'C', 'D', 'E', 'F', 'G'].map((k) => [k, {}]));
    expect(findings({ [A]: { ...axes, country: { ...axes.country, count: 7 } }, 'src/world/gazetteer/countries.json': many, ...weatherRows([]) })).toEqual([
      `red ${W} | 7 keys of the axis "country" have no row (first: A, B, C, D, E)`,
    ]);
  });
  it("fails an axis whose universe isn't the owner's count", () => {
    expect(findings({ 'src/world/gazetteer/countries.json': { FR: {}, DE: {}, XX: {}, YY: {} } })).toEqual([
      'red src/world/gazetteer/countries.json | the axis "country" holds 4 keys, but the owner\'s count is 3 (KEEP 19)',
      `red ${W} | 1 keys of the axis "country" have no row (first: YY)`,
    ]);
  });
  it('fails a researched row that cites nothing found, or cites a blocker or the game', () => {
    const cite = (reg: unknown[]) => findings(weatherRows([{ ...rows[0], register: reg }, rows[1], rows[2]]));
    expect(cite([])).toEqual([`red ${W} FR | a researched row cites a found fact`]);
    expect(cite(['R-0001', 'R-0002'])).toEqual([`red ${W} FR | a researched row cites only found facts`]);
    expect(cite(['R-0004', 'R-0003'])).toEqual([`red ${W} FR | a researched row cites only found facts`]);
    expect(cite(['R-9999'])).toEqual([`red ${W} FR | the row cites R-9999, which the register doesn't hold`, `red ${W} FR | a researched row cites a found fact`]);
    expect(cite([7])).toEqual([`red ${W} FR | the row cites 7, which the register doesn't hold`, `red ${W} FR | a researched row cites a found fact`]);
    expect(findings(weatherRows([{ ...rows[0], register: undefined }, rows[1], rows[2]]))).toEqual([`red ${W} FR | a researched row cites a found fact`]);
  });
  it('fails a blocked row without its blocker, and a game row without the game figure', () => {
    expect(findings(weatherRows([rows[0], { ...rows[1], status: 'game', register: [] }, { ...rows[2], register: ['R-0001'] }]))).toEqual([
      `red ${W} DE | a row standing on the game's own figure cites it`,
      `red ${W} XX | a blocked row cites its blocker`,
    ]);
    expect(findings(weatherRows([rows[0], { ...rows[1], status: 'game', register: ['R-0003'] }, rows[2]]))).toEqual([]);
  });
  it('fails a done row with no test, or one that did not pass; a pending row needs none', () => {
    expect(findings(weatherRows([{ ...rows[0], tests: [] }, { ...rows[1], tests: ['x::y'] }, { key: 'XX', status: 'pending', tests: ['x::y'] }]))).toEqual([
      `red ${W} FR | the row names no test that holds it`,
      `red ${W} DE | the row's test didn't pass in this run: x::y`,
      'incomplete - | 1 coverage rows are pending',
    ]);
    expect(findings(weatherRows([{ ...rows[0], tests: undefined }, rows[1], rows[2]]))).toEqual([`red ${W} FR | the row names no test that holds it`]);
  });
  it('fails an engine that reads a place without the country axis, or without a run over every place', () => {
    const placeOnly = { [E]: { ...engines, 'world.weather': { ...weather, matrices: ['coverage/w2.json'] } }, 'coverage/w2.json': { engine: 'world.weather', axis: 'place', rows: ['1', '2', '3', '4'].map((key) => ({ key, status: 'proven', tests: [T] })) } };
    expect(findings(placeOnly)).toEqual(['red registry/engines.json world.weather | the engine reads a place, so it covers the country axis']);
    expect(findings({}, new Set([T]))).toEqual(['red registry/engines.json world.weather | the engine reads a place, so a passing test runs it over every place of the map (allPlacesTest)']);
    expect(findings({ [E]: { ...engines, 'world.weather': { ...weather, allPlacesTest: undefined } } })).toEqual(['red registry/engines.json world.weather | the engine reads a place, so a passing test runs it over every place of the map (allPlacesTest)']);
  });
  it('reads an engine-specific universe, by keys, array or field', () => {
    const own = (universe: unknown, data: unknown, rowKeys = ['weather.day']) =>
      findings({ [E]: { ...engines, 'core.rng': { layer: 1, dir: 'src/core/rng', readsPlace: false, matrices: ['coverage/rng.json'] } }, 'src/core/rng/rng.ts': 'export {};\n', 'src/core/rng/deciders.json': data, 'coverage/rng.json': { engine: 'core.rng', axis: 'decider', universe, rows: rowKeys.map((key) => ({ key, status: 'proven', tests: [T] })) } });
    const M = 'coverage/rng.json';
    expect(own({ source: 'src/core/rng/deciders.json', pick: 'keys' }, { 'weather.day': 1 })).toEqual([]);
    expect(own({ source: 'src/core/rng/deciders.json', pick: 'array' }, ['weather.day'])).toEqual([]);
    expect(own({ source: 'src/core/rng/deciders.json', pick: 'field:id' }, [{ id: 'weather.day' }])).toEqual([]);
    expect(own({ source: 'src/core/rng/deciders.json', pick: 'field:id' }, [{ id: 'weather.day' }, { name: 'x' }])).toEqual([`red ${M} | the axis "decider" can't be read: src/core/rng/deciders.json: not every item has a string "id"`]);
    expect(own({ source: 'src/core/rng/deciders.json', pick: 'field:id' }, [{ id: 'weather.day' }, 'x'])).toEqual([`red ${M} | the axis "decider" can't be read: src/core/rng/deciders.json: not every item has a string "id"`]);
    expect(own({ source: 'src/core/rng/deciders.json', pick: 'keys' }, ['x'])).toEqual([`red ${M} | the axis "decider" can't be read: src/core/rng/deciders.json is not an object`]);
    expect(own({ source: 'src/core/rng/deciders.json', pick: 'array' }, ['weather.day', 1])).toEqual([`red ${M} | the axis "decider" can't be read: src/core/rng/deciders.json is not an array of strings`]);
    expect(own({ source: 'src/core/rng/deciders.json', pick: 'array' }, { a: 1 })).toEqual([`red ${M} | the axis "decider" can't be read: src/core/rng/deciders.json is not an array of strings`]);
    for (const pick of ['sideways', 'xfield:id', 'field:', 'field:id\nx']) {
      const out = own({ source: 'src/core/rng/deciders.json', pick }, [{ id: 'weather.day' }]);
      expect(out).toEqual([`red ${M} | the axis "decider" can't be read: pick "${pick}" is keys, array or field:<name>`]);
    }
    expect(own({ source: 'src/core/rng/deciders.json', pick: 'field:id' }, { 'weather.day': 1 })).toEqual([`red ${M} | the axis "decider" can't be read: pick "field:id" is keys, array or field:<name>`]);
    expect(own(undefined, ['x'])).toEqual([`red ${M} | the axis "decider" is neither a declared axis nor given a universe here`]);
    expect(own({ source: 'src/core/rng/deciders.json', pick: 'keys:inner' }, { inner: { 'weather.day': 1 } })).toEqual([]);
    for (const data of [{ inner: ['weather.day'] }, { other: {} }, ['x']]) {
      expect(own({ source: 'src/core/rng/deciders.json', pick: 'keys:inner' }, data)).toEqual([`red ${M} | the axis "decider" can't be read: src/core/rng/deciders.json has no object "inner"`]);
    }
    expect(own({ keys: ['weather.day'] }, 'unread')).toEqual([]);
    expect(own({ keys: ['weather.day', 'other.one'] }, 'unread')).toEqual([`red ${M} | 1 keys of the axis "decider" have no row (first: other.one)`]);
    for (const keys of [[], ['a', 3], 'a']) expect(own({ keys }, 'unread')).toEqual([`red ${M} | the axis "decider" is neither a declared axis nor given a universe here`]);
    expect(own({ source: 'src/core/rng/deciders.json' }, ['x'])).toEqual([`red ${M} | the axis "decider" is neither a declared axis nor given a universe here`]);
    expect(own({ source: 'src/core/rng/none.json', pick: 'keys' }, ['x'])).toEqual([`red ${M} | the axis "decider" can't be read: src/core/rng/none.json is missing`]);
  });
  it('fails engine code that no engine declares, and a file loose in an engine layer, in every directory of the layer', () => {
    expect(findings({ 'src/world/prices/prices.ts': 'export {};\n', 'src/world/prices/deep/x.ts': 'export {};\n', 'src/world/loose.ts': 'export {};\n', 'src/core/README.md': 'x', 'src/places/odd/o.ts': 'x', 'src/ui/free.tsx': 'x' })).toEqual([
      'red src/core/README.md | a file sits loose in a layer that holds engines; it belongs to an engine\'s directory',
      'red src/world/prices | a directory of engine code that no engine in the registry declares',
      'red src/world/loose.ts | a file sits loose in a layer that holds engines; it belongs to an engine\'s directory',
      'red src/places/odd | a directory of engine code that no engine in the registry declares',
    ]);
  });
  it("fails an engine with an empty directory, outside its layer, or with a matrix that isn't its own", () => {
    expect(findings({ [E]: { ...engines, 'world.empty': { ...gazetteer, dir: 'src/world/empty', matrices: ['coverage/empty.json'] } }, 'coverage/empty.json': { engine: 'world.empty', axis: 'place', rows: ['1', '2', '3', '4'].map((key) => ({ key, status: 'proven', tests: [T] })) } })).toEqual(['red registry/engines.json world.empty | the engine\'s directory src/world/empty holds nothing']);
    expect(findings({ [E]: { ...engines, 'world.gazetteer': { ...gazetteer, layer: 1 } } })).toEqual(["red registry/engines.json world.gazetteer | the engine's directory isn't inside layer 1"]);
    expect(findings({ [E]: { ...engines, 'world.gazetteer': { ...gazetteer, layer: 9 } } })).toEqual(["red registry/engines.json world.gazetteer | the engine's directory isn't inside layer 9"]);
    // Without a readable ledger, an engine's layer can't be held; the build-order check reports the ledger.
    expect(all(checkCoverage(fixture(files({ [E]: { ...engines, 'world.gazetteer': { ...gazetteer, layer: 9 } } })).repo, undefined, register, { passed }))).toEqual([]);
    expect(findings({ [G]: { engine: 'world.weather', axis: 'place', rows: [] } })).toEqual([`red ${G} | a matrix needs engine "world.gazetteer", its axis and its rows`]);
    expect(findings({ [G]: { engine: 'world.gazetteer', axis: '', rows: [] } })).toEqual([`red ${G} | a matrix needs engine "world.gazetteer", its axis and its rows`]);
    expect(findings({ [G]: { engine: 'world.gazetteer', axis: 'place', rows: {} } })).toEqual([`red ${G} | a matrix needs engine "world.gazetteer", its axis and its rows`]);
    expect(findings({ [G]: [] })).toEqual([`red ${G} | a matrix needs engine "world.gazetteer", its axis and its rows`]);
    expect(findings({ [G]: 'null' })).toEqual([`red ${G} | a matrix needs engine "world.gazetteer", its axis and its rows`]);
    expect(findings({ [E]: { ...engines, 'world.gazetteer': { ...gazetteer, matrices: ['coverage/none.json'] } } })).toEqual(['red coverage/none.json | coverage/none.json is missing']);
  });
  it('fails a malformed engine, matrix entry, row or axis', () => {
    const engineAt = 'red registry/engines.json x | an engine needs layer, dir, readsPlace and at least one matrix';
    for (const bad of [{ ...gazetteer, layer: '2' }, { ...gazetteer, dir: '' }, { ...gazetteer, readsPlace: 'no' }, { ...gazetteer, matrices: 'x' }, { ...gazetteer, matrices: [] }, 'x']) {
      expect(findings({ [E]: { ...engines, x: bad } })).toEqual([engineAt]);
    }
    expect(findings({ [E]: { ...engines, 'world.gazetteer': { ...gazetteer, matrices: [3, G] } } })).toEqual(['red registry/engines.json world.gazetteer | a matrix is named by its path']);
    const rowAt = `red ${W} row 3 | a row needs its key and a status (researched, proven, blocked, game, pending)`;
    for (const bad of [{ key: 'FR' }, { key: '', status: 'proven' }, { status: 'proven' }, 'x']) expect(findings(weatherRows([...rows, bad]))).toEqual([rowAt]);
    const axisAt = (n: string) => `red ${A} ${n} | an axis needs source, pick, the count the owner decided, and where it was decided`;
    for (const bad of [{ source: 'x' }, { ...axes.place, count: '4' }, { ...axes.place, decidedIn: '' }, { ...axes.place, source: '' }, 'x']) {
      expect(findings({ [A]: { ...axes, extra: bad } })).toEqual([axisAt('extra')]);
    }
  });
  it("holds no universe to a count that isn't a number", () => {
    expect(findings({ [A]: { ...axes, country: { ...axes.country, count: '3' } } })).toEqual([`red ${A} country | an axis needs source, pick, the count the owner decided, and where it was decided`]);
  });
  it('fails without the country or the place axis', () => {
    const noCountry = findings({ [A]: { place: axes.place } });
    expect(noCountry[0]).toBe(`red ${A} | the country axis is not declared`);
    expect(findings({ [A]: { country: axes.country } })).toEqual([`red ${A} | the place axis is not declared`, `red ${G} | the axis "place" is neither a declared axis nor given a universe here`]);
    expect(findings({ [A]: { ...axes, place: 'x' } })).toEqual([`red ${A} place | an axis needs source, pick, the count the owner decided, and where it was decided`, `red ${A} | the place axis is not declared`, `red ${G} | the axis "place" is neither a declared axis nor given a universe here`]);
  });
  it('fails a missing or malformed registry', () => {
    const only = (f: Record<string, unknown>) => all(checkCoverage(fixture(f).repo, ledger, register, { passed }));
    expect(only({ [A]: axes })).toEqual([`red ${E} | ${E} is missing`]);
    expect(only({ [E]: {} })).toEqual([`red ${A} | ${A} is missing`]);
    expect(only({ [E]: [], [A]: axes })).toEqual([`red ${E} | the engine registry is not an object`]);
    expect(only({ [E]: {}, [A]: [] })).toEqual([`red ${A} | the axis registry is not an object`]);
  });
});
