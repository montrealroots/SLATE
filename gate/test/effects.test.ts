import { describe, expect, it } from 'vitest';
import { checkEffects, scanConsumers, scanDeclarations } from '../checks/effects.ts';
import type { FalsifierRecord } from '../checks/features.ts';
import { all, fixture } from './fixture.ts';

const R = 'registry/effects.json';
const ENGINE = 'src/money/thing/thing.ts';
const engine = `import { defineCommand, defineKind, defineNotice } from '../../core/frame/frame.ts';
export const DONE = defineNotice('thing.done');
export const TICK = 'thing.tick';
defineKind<Holding>({ kind: TICK, wants: false, reads: [], writes: ['thing'], happen: tick });
export const make = defineCommand<H, A>({ id: 'thing.make', reads: [], writes: ['thing'], run: run });
`;
const READER = 'src/money/other/other.ts';
const reader = `export function use(s) {
  // @slate:consumer thing.make
  // @slate:consumer thing.tick
  return s.thing.count;
}
`;
const registry = { 'thing.make': { what: 'Makes a thing.' }, 'thing.tick': { what: 'Ticks.' }, 'thing.done': { what: 'Says so.', awaits: 'layer 5: the screen' } };
const T = 'tests/thing.test.ts';
const proofs: FalsifierRecord[] = [
  { feature: 'thing.make', claim: 'bites', file: T, test: 'thing > makes' },
  { feature: 'thing.tick', claim: 'bites', file: T, test: 'thing > ticks' },
];
const passed = new Set(proofs.map((p) => `${p.file}::${p.test}`));
const findings = (over: Record<string, unknown> = {}, p: FalsifierRecord[] = proofs, ok: ReadonlySet<string> = passed) =>
  all(checkEffects(fixture({ [R]: registry, [ENGINE]: engine, [READER]: reader, 'src/core/frame/frame.ts': "defineNotice('frame.own');", ...over }).repo, p, { passed: ok }));

describe('the declarations', () => {
  it('are each command, notice and kind, a kind named by its constant or as written', () => {
    expect(scanDeclarations(ENGINE, engine)).toEqual([
      { id: 'thing.done', sort: 'notice', file: ENGINE, line: 2 },
      { id: 'thing.tick', sort: 'kind', file: ENGINE, line: 4 },
      { id: 'thing.make', sort: 'command', file: ENGINE, line: 5 },
    ]);
    // However the code is spaced, and a kind's constant exported or not.
    const spaced = "const  K  =  'k.b';\nexport  const L = 'k.c';\ndefineKind({  kind:  K });\ndefineKind({kind:L});\ndefineCommand({  id:  'c.b' });\ndefineCommand({id:'c.c'});\ndefineNotice(  'n.b'  );\ndefineNotice('n.c');";
    expect(scanDeclarations('g.ts', spaced).map((d) => `${d.sort} ${d.id}`)).toEqual(['kind k.b', 'kind k.c', 'command c.b', 'command c.c', 'notice n.b', 'notice n.c']);
    expect(scanDeclarations('f.ts', "defineKind({ kind: 'k.a', wants: true });\ndefineCommand({ id: 'c.a' });\ndefineKind({ kind: UNKNOWN });")).toEqual([
      { id: 'k.a', sort: 'kind', file: 'f.ts', line: 1 },
      { id: 'c.a', sort: 'command', file: 'f.ts', line: 2 },
    ]);
  });

  it("are read where an anchor vouches for its own line, or the next line of code under it", () => {
    expect(scanConsumers('f.ts', '  // @slate:consumer a.b\n\n  // more\n  read(); // @slate:consumer c.d\n')).toEqual([
      { id: 'a.b', file: 'f.ts', line: 4 },
      { id: 'c.d', file: 'f.ts', line: 4 },
    ]);
    expect(scanConsumers('f.ts', '// @slate:consumer a.b\n')).toEqual([]);
    expect(scanConsumers('f.ts', 'x(); // @slate:consumer   e.f\n')).toEqual([{ id: 'e.f', file: 'f.ts', line: 1 }]);
  });
});

describe('the effects check', () => {
  it('passes when each is registered, read (or awaits a later layer), and each command and kind falsified', () => {
    expect(findings()).toEqual([]);
    // A test file's declarations aren't the code's; a consumer in the declaring file, on another line, reads it.
    expect(findings({ 'src/money/thing/thing.test.ts': "defineNotice('thing.test');" })).toEqual([]);
    expect(findings({ [READER]: '// @slate:consumer thing.tick\nx();\n', [ENGINE]: `${engine}// @slate:consumer thing.make\nuse();\n` })).toEqual([]);
    // Two readers and two proofs are each listed; a command no test falsifies shows as missing.
    const two = checkEffects(
      fixture({ [R]: registry, [ENGINE]: engine, [READER]: reader, 'src/b.ts': '// @slate:consumer thing.make\nb();\n' }).repo,
      [...proofs, { feature: 'thing.make', claim: 'bites', file: T, test: 'thing > makes again' }],
      { passed: new Set([...passed, `${T}::thing > makes again`]) },
    );
    expect(two.check).toBe('effects');
    expect(two.generated[0]?.content).toBe(
      [
        "# The Engines' Effects",
        '',
        'Generated by the gate from the declarations in `src/`, `registry/effects.json`, the `@slate:consumer` anchors and',
        'the falsifiers recorded by the last test run; do not edit by hand. Every command, scheduled kind and notice is read',
        'by code that changes an outcome by it (or awaits the layer that will read it), and every command and kind is',
        'falsified: changing its input changes the state it leaves.',
        '',
        'Effects: 3.',
        '',
        '| Effect | Sort | Declared | What it changes | Read at | Falsified by |',
        '|---|---|---|---|---|---|',
        '| `thing.done` | notice | `src/money/thing/thing.ts:2` | Says so. | awaits: layer 5: the screen | left for its reader |',
        '| `thing.make` | command | `src/money/thing/thing.ts:5` | Makes a thing. | `src/b.ts:2`<br>`src/money/other/other.ts:4` | tests/thing.test.ts › thing > makes<br>tests/thing.test.ts › thing > makes again |',
        '| `thing.tick` | kind | `src/money/thing/thing.ts:4` | Ticks. | `src/money/other/other.ts:4` | tests/thing.test.ts › thing > ticks |',
        '',
      ].join('\n'),
    );
    const missing = checkEffects(fixture({ [R]: registry, [ENGINE]: engine, [READER]: reader }).repo, [], { passed: new Set() });
    expect(missing.generated[0]?.content).toContain('| tests/thing.test.ts › thing > ticks |'.replace('tests/thing.test.ts › thing > ticks', '**missing**'));
    const r = checkEffects(fixture({ [R]: registry, [ENGINE]: engine, [READER]: reader }).repo, proofs, { passed });
    expect(r.notes).toEqual(['3 effects, 2 consumer anchors, 2 falsifiers accepted']);
    // A proof for something not declared here (a page's feature) isn't counted.
    const other = checkEffects(fixture({ [R]: registry, [ENGINE]: engine, [READER]: reader }).repo, [...proofs, { feature: 'page.x', claim: 'bites', file: T, test: 'x' }], { passed: new Set([...passed, `${T}::x`]) });
    expect(other.notes).toEqual(['3 effects, 2 consumer anchors, 2 falsifiers accepted']);
    expect(r.generated[0]?.path).toBe('matrix/EFFECTS.md');
    expect(r.generated[0]?.content).toContain("| `thing.done` | notice | `src/money/thing/thing.ts:2` | Says so. | awaits: layer 5: the screen | left for its reader |");
    expect(r.generated[0]?.content).toContain('| `thing.make` | command | `src/money/thing/thing.ts:5` | Makes a thing. | `src/money/other/other.ts:4` | tests/thing.test.ts › thing > makes |');
    expect(r.generated[0]?.content).toContain('Effects: 3.');
  });

  it("is red on an effect not registered, registered and not declared, or named by a consumer and not declared", () => {
    expect(findings({ [R]: { ...registry, 'thing.gone': { what: 'x' } } })).toEqual([`red ${R} thing.gone | a registered effect that no code declares`]);
    expect(findings({ [R]: { 'thing.tick': registry['thing.tick'], 'thing.done': registry['thing.done'] } })).toEqual([`red ${ENGINE}:5 | the command thing.make isn't registered in ${R} with what it changes`]);
    expect(findings({ [R]: { ...registry, 'thing.make': { what: '' } } })).toEqual([`red ${ENGINE}:5 | the command thing.make isn't registered in ${R} with what it changes`]);
    expect(findings({ [R]: { ...registry, 'thing.make': 'x' } })).toEqual([`red ${ENGINE}:5 | the command thing.make isn't registered in ${R} with what it changes`]);
    expect(findings({ 'src/x.ts': '// @slate:consumer thing.nope\nx();\n' })).toEqual(['red src/x.ts:2 | a consumer anchor names "thing.nope", which no code declares']);
    expect(findings({ [R]: [] })).toEqual([`red ${R} | the effects registry is not an object`]);
    expect(findings({ [R]: '{' })[0]).toMatch(/^red registry\/effects\.json \| /);
  });

  it('is red on an effect nothing reads, one read that still says it awaits, and an awaiting not said in words', () => {
    expect(findings({ [READER]: 'x();\n' })).toEqual([
      `red ${ENGINE}:5 | nothing reads the command thing.make: anchor its consumer (@slate:consumer thing.make) or say what layer it awaits`,
      `red ${ENGINE}:4 | nothing reads the kind thing.tick: anchor its consumer (@slate:consumer thing.tick) or say what layer it awaits`,
    ]);
    expect(findings({ 'src/y.ts': '// @slate:consumer thing.done\nshow();\n', 'src/z.ts': '// @slate:consumer thing.done\nshow();\n' })).toEqual([
      `red ${R} thing.done | the notice thing.done is read now (src/y.ts:2, src/z.ts:2), so it awaits nothing`,
    ]);
    expect(findings({ [R]: { ...registry, 'thing.done': { what: 'x', awaits: 5 } } })).toEqual([`red ${R} thing.done | an effect awaits a later layer, named in words`]);
    // An anchor on the declaration's own line doesn't read it.
    expect(findings({ [READER]: 'x();\n', [ENGINE]: engine.replace("run: run });", 'run: run }); // @slate:consumer thing.make') })).toContain(
      `red ${ENGINE}:5 | nothing reads the command thing.make: anchor its consumer (@slate:consumer thing.make) or say what layer it awaits`,
    );
  });

  it('is red on a command or a kind no passing test falsifies; a notice needs none', () => {
    expect(findings({}, [])).toEqual([
      `red ${ENGINE}:5 | no passing test falsifies the command thing.make (falsifyAny with claim 'bites')`,
      `red ${ENGINE}:4 | no passing test falsifies the kind thing.tick (falsifyAny with claim 'bites')`,
    ]);
    expect(findings({}, proofs, new Set([`${T}::thing > ticks`]))).toEqual([`red ${ENGINE}:5 | no passing test falsifies the command thing.make (falsifyAny with claim 'bites')`]);
    expect(findings({}, proofs.map((p) => ({ ...p, claim: 'downstream' })))).toHaveLength(2);
  });
});
