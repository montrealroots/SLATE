import { describe, expect, it } from 'vitest';
import { METHODS, checkRegister } from '../checks/register.ts';
import { all, fixture } from './fixture.ts';

const TODAY = '2026-10-26';
const R = 'research/register.json';
const primary = { kind: 'primary', url: 'https://www.iana.org/time-zones', title: 'Time Zone Database', read: '2026-10-26', said: 'Release 2026c' };
const found = (over: Record<string, unknown> = {}) => ({ id: 'R-0001', fact: 'tz.release', sought: 'The current tz release', status: 'found', value: '2026c', sources: [primary], ...over });
const attempts = METHODS.map((method) => ({ method, tried: `tried by ${method}`, result: 'nothing', date: '2026-10-25' }));
const blocked = (over: Record<string, unknown> = {}) => ({ id: 'R-0002', fact: 'bank.xx.fees', sought: 'Fees of banks in XX', status: 'blocked', attempts, notModeled: 'money.not-modeled', ...over });
const game = (over: Record<string, unknown> = {}) => ({ id: 'R-0003', fact: 'game.start-hour', sought: 'The hour a life opens', status: 'game', why: 'Nothing real sets it', playerLabel: 'home.game-figure', ...over });
const ids = new Set(['money.not-modeled', 'home.game-figure']);
const run = (entries: unknown[]) => checkRegister(fixture({ [R]: { entries } }).repo, TODAY, ids);
const findings = (entries: unknown[]) => all(run(entries).result);

describe('the research register check', () => {
  it('passes a found fact, a blocker tried every way, and a labeled game figure, and indexes them', () => {
    const { result, index } = run([found(), blocked(), game()]);
    expect(all(result)).toEqual([]);
    expect(result.check).toBe('research-register');
    expect([...index.entries.values()]).toEqual([
      { id: 'R-0001', fact: 'tz.release', status: 'found' },
      { id: 'R-0002', fact: 'bank.xx.fees', status: 'blocked' },
      { id: 'R-0003', fact: 'game.start-hour', status: 'game' },
    ]);
    expect(result.notes).toEqual(['3 register entries (1 found, 0 secondary, 1 blocked, 1 game)']);
    expect(result.generated).toEqual([
      {
        path: 'matrix/REGISTER.md',
        content: [
          '# The Research Register, In Brief',
          '',
          'Generated by the gate from `research/register.json`; do not edit by hand. The register itself holds the sources,',
          'the dates and the attempts.',
          '',
          'Entries: 3 (1 found, 0 secondary, 1 blocked, 1 game).',
          '',
          '| Id | Fact | Status |',
          '|---|---|---|',
          '| R-0001 | `tz.release` | found |',
          '| R-0002 | `bank.xx.fees` | blocked |',
          '| R-0003 | `game.start-hour` | game |',
          '',
        ].join('\n'),
      },
    ]);
  });
  it('passes a secondary fact that names the primary it quotes, and a plain http page', () => {
    const s = { ...primary, kind: 'secondary', url: 'http://variety.com/x', quotes: 'https://www.sagaftra.org/rule' };
    expect(findings([found({ status: 'secondary', sources: [s] })])).toEqual([]);
  });
  it('fails an entry without a well-formed id, or with one used twice', () => {
    for (const id of ['X-1', 'R-001', 'xR-0001', 'R-0001x', 7]) expect(findings([found({ id })])).toEqual([`red ${R} entry 0 | an entry needs an id like R-0001`]);
    expect(findings([found(), found({ fact: 'other' })])).toEqual([`red ${R} R-0001 | the id R-0001 is used twice`]);
    expect(findings(['not an entry', null])).toEqual([`red ${R} entry 0 | an entry is not an object`, `red ${R} entry 1 | an entry is not an object`]);
  });
  it('fails an entry without its fact, what was sought, or a known status', () => {
    const noFacts = run([found({ fact: '' }), found({ id: 'R-0002', fact: '' })]);
    expect(all(noFacts.result)).toEqual([`red ${R} R-0001 | an entry needs the fact key it holds`, `red ${R} R-0002 | an entry needs the fact key it holds`]);
    expect(noFacts.index.entries.get('R-0001')).toEqual({ id: 'R-0001', fact: '', status: 'found' });
    expect(findings([found({ sought: ' ' })])).toEqual([`red ${R} R-0001 | an entry needs what was sought, in words`]);
    expect(findings([found({ status: 'guessed' })])).toEqual([`red ${R} R-0001 | status must be one of found, secondary, blocked, game`]);
  });
  it('fails a second copy of a fact', () => {
    expect(findings([found(), found({ id: 'R-0009' })])).toEqual([`red ${R} R-0009 | the fact "tz.release" is held twice, by R-0001 and R-0009`]);
  });
  it('fails a source without its page, title, words or date', () => {
    const at = `${R} R-0001 source 0`;
    const with_ = (s: Record<string, unknown>) => findings([found({ sources: [{ ...primary, ...s }] })]);
    for (const url of ['iana.org', 'see https://iana.org', 'https://iana.org x', 'ftp://iana.org', undefined]) expect(with_({ url })).toEqual([`red ${at} | a source needs the page it was read from, as a URL`]);
    expect(with_({ title: '' })).toEqual([`red ${at} | a source needs its title`]);
    expect(with_({ said: '' })).toEqual([`red ${at} | a source needs what it said`]);
    for (const read of ['26/10/2026', '2026-02-30', 20261026]) expect(with_({ read })).toEqual([`red ${at} | a source needs the date it was read, as YYYY-MM-DD`]);
    expect(with_({ read: '2026-10-27' })).toEqual([`red ${at} | a source is dated 2026-10-27, after today (2026-10-26)`]);
    expect(with_({ kind: 'blog' })).toEqual([`red ${at} | a source is "primary" or "secondary"`, `red ${R} R-0001 | a found fact needs its primary source`]);
    expect(findings([found({ sources: [primary, 'x', null] })])).toEqual([`red ${R} R-0001 source 1 | a source is not an object`, `red ${R} R-0001 source 2 | a source is not an object`]);
  });
  it('fails a found or secondary fact without its source or its value', () => {
    expect(findings([found({ sources: [] })])).toEqual([`red ${R} R-0001 | a found fact needs its primary source`]);
    expect(findings([found({ sources: undefined })])).toEqual([`red ${R} R-0001 | a found fact needs its primary source`]);
    const { value: _f, ...noValue } = found();
    expect(findings([noValue])).toEqual([`red ${R} R-0001 | a found fact needs its value`]);
    const s = { ...primary, kind: 'secondary', quotes: 'https://x.org/a' };
    const { value: _s, ...secondaryNoValue } = found({ status: 'secondary', sources: [s] });
    expect(findings([secondaryNoValue])).toEqual([`red ${R} R-0001 | a found fact needs its value`]);
    expect(findings([found({ value: null })])).toEqual([]);
  });
  it('fails a secondary fact that names no primary, or has no secondary source', () => {
    expect(findings([found({ status: 'secondary', sources: [{ ...primary, kind: 'secondary' }] })])).toEqual([`red ${R} R-0001 source 0 | a secondary source must name the primary it quotes`]);
    expect(findings([found({ status: 'secondary' })])).toEqual([`red ${R} R-0001 | a fact marked secondary needs the secondary source it was found in`]);
  });
  it('fails a blocker that skipped a method, or a malformed attempt', () => {
    const at = `${R} R-0002`;
    expect(findings([blocked({ attempts: attempts.filter((a) => a.method !== 'archive') })])).toEqual([`red ${at} | a blocker stands only after every method; "archive" wasn't tried`]);
    expect(findings([blocked({ attempts: undefined })])).toEqual(METHODS.map((m) => `red ${at} | a blocker stands only after every method; "${m}" wasn't tried`));
    const methods = `an attempt's method is one of ${METHODS.join(', ')}`;
    expect(findings([blocked({ attempts: [...attempts, { method: 'asked a friend' }, 'x'] })])).toEqual([`red ${at} attempt 5 | ${methods}`, `red ${at} attempt 6 | ${methods}`]);
    const a0 = attempts[0] as Record<string, unknown>;
    expect(findings([blocked({ attempts: [...attempts, { ...a0, tried: '' }] })])).toEqual([`red ${at} attempt 5 | an attempt says what was tried (the query, the page)`]);
    expect(findings([blocked({ attempts: [...attempts, { ...a0, result: '' }] })])).toEqual([`red ${at} attempt 5 | an attempt says what came of it`]);
    expect(findings([blocked({ attempts: [...attempts, { ...a0, date: 'yesterday' }] })])).toEqual([`red ${at} attempt 5 | an attempt needs the date it was read, as YYYY-MM-DD`]);
  });
  it("fails a blocker without the line that tells the player what isn't modeled", () => {
    const at = `${R} R-0002`;
    expect(findings([blocked({ notModeled: undefined })])).toEqual([`red ${at} | a blocker's line telling the player what isn't modeled must name a line of the text catalog`]);
    expect(findings([blocked({ notModeled: 'nowhere.line' })])).toEqual([`red ${at} | a blocker's line telling the player what isn't modeled names "nowhere.line", which the text catalog doesn't hold`]);
    // Before the catalog exists (layer 0), only the line's presence can be held.
    expect(all(checkRegister(fixture({ [R]: { entries: [blocked({ notModeled: 'nowhere.line' })] } }).repo, TODAY, undefined).result)).toEqual([]);
  });
  it("fails the game's own figure without its reason or its label", () => {
    expect(findings([game({ why: '' })])).toEqual([`red ${R} R-0003 | the game's own figure needs the reason nothing real stands there`]);
    expect(findings([game({ playerLabel: 'x.y' })])).toEqual([`red ${R} R-0003 | the game's own figure's label to the player names "x.y", which the text catalog doesn't hold`]);
  });
  it('fails a missing or malformed register', () => {
    expect(all(checkRegister(fixture({}).repo, TODAY, ids).result)).toEqual([`red ${R} | ${R} is missing`]);
    for (const bad of [{ entries: {} }, [], 'null']) expect(all(checkRegister(fixture({ [R]: bad }).repo, TODAY, ids).result)).toEqual([`red ${R} | the register needs an "entries" array`]);
  });
});
