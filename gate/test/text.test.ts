import { describe, expect, it } from 'vitest';
import { VOICE_LAYER, checkText } from '../checks/text.ts';
import { all, fixture } from './fixture.ts';

const V = 'registry/voice.json';
const C = 'src/core/text/catalog.json';
const voice = { source: 'docs/KEEP.md entry 2', banned: [{ pattern: '\\bslots?\\b', why: 'a life, never a slot' }] };
const line = (text: string, over: Record<string, unknown> = {}) => ({ text, where: 'The slots screen, the empty card', status: 'placeholder', ...over });
const repo = (catalog: unknown, code = "t('slots.empty.body');\n", files: Record<string, unknown> = {}) => fixture({ [V]: voice, [C]: catalog, 'src/ui/slots/Slots.tsx': code, ...files }).repo;
const findings = (catalog: unknown, code?: string, layer = 1) => all(checkText(repo(catalog, code), layer).result);

describe('the text inventory check', () => {
  it('passes a catalog whose every line is said, in the voice, and writes the inventory', () => {
    const { result, ids } = checkText(repo({ 'slots.empty.body': line('Nobody here yet, {name}.'), 'slots.foot.device': line('Kept here.', { where: 'The foot', status: 'owner' }) }, "t('slots.empty.body'); t('slots.foot.device');"), 1);
    expect(all(result)).toEqual([]);
    expect(result.check).toBe('text-inventory');
    expect(ids).toEqual(new Set(['slots.empty.body', 'slots.foot.device']));
    expect(result.notes).toEqual(['2 lines in the catalog, 1 placeholder']);
    expect(result.generated).toEqual([
      {
        path: 'matrix/TEXT.md',
        content: [
          '# Every Line The Game Says',
          '',
          'Generated by the gate from `src/core/text/catalog.json`; do not edit by hand. Placeholder lines are the',
          "builder's draft in the voice standard (KEEP entry 2); the owner's wording replaces them.",
          '',
          "Lines: 2 (1 placeholder, 1 the owner's).",
          '',
          '| Where | Id | Text | Wording |',
          '|---|---|---|---|',
          '| The slots screen, the empty card | `slots.empty.body` | Nobody here yet, {name}. | placeholder |',
          '| The foot | `slots.foot.device` | Kept here. | owner |',
          '',
        ].join('\n'),
      },
    ]);
  });
  it('notes, and holds nothing, before the catalog exists', () => {
    const { result, ids } = checkText(fixture({ [V]: voice }).repo, 0);
    expect(all(result)).toEqual([]);
    expect(result.notes).toEqual(['no text catalog yet: the first player-facing line arrives with layer 1']);
    expect(result.generated).toEqual([]);
    expect(ids).toBeUndefined();
  });
  it('fails a line nothing says, and counts neither the catalog nor a test as saying it', () => {
    const r = checkText(repo({ 'slots.empty.body': line('Nobody here yet.') }, "t('slots.other');\n", { 'src/ui/slots/Slots.test.tsx': "t('slots.empty.body')" }), 1);
    expect(all(r.result)).toEqual([`red ${C} slots.empty.body | nothing in the game says this line`]);
  });
  it('finds a line said in any one file, in any quoting, and only as a whole id', () => {
    const c = { 'slots.empty.body': line('x') };
    expect(all(checkText(repo(c, "t('other');", { 'src/ui/slots/Other.tsx': "t('slots.empty.body')" }), 1).result)).toEqual([]);
    expect(findings(c, 't("slots.empty.body")')).toEqual([]);
    expect(findings(c, 't(`slots.empty.body`)')).toEqual([]);
    expect(findings(c, "t('slotsXempty.body')")).toEqual([`red ${C} slots.empty.body | nothing in the game says this line`]);
    expect(findings(c, "t('slots.empty.body\")")).toEqual([`red ${C} slots.empty.body | nothing in the game says this line`]);
  });
  it("fails the engine's vocabulary in the words, not in a value's slot", () => {
    expect(findings({ 'slots.empty.body': line('An empty slot.') })).toEqual([`red ${C} slots.empty.body | the line uses the engine's vocabulary (a life, never a slot): "An empty slot."`]);
    expect(findings({ 'slots.empty.body': line('Hello {slot}.') })).toEqual([]);
    expect(findings({ 'slots.empty.body': line('Hello {name}, your slot.') })).toEqual([`red ${C} slots.empty.body | the line uses the engine's vocabulary (a life, never a slot): "Hello {name}, your slot."`]);
    expect(findings({ 'slots.empty.body': line('SLOTS') })).toHaveLength(1);
  });
  it('fails a malformed id, line, status or value slot', () => {
    expect(findings({ Slots: line('x') }, "t('Slots')")).toEqual([`red ${C} Slots | a line id is dotted lower-case words, like "slots.empty.body"`]);
    expect(findings({ 'x.slots': line('x') }, "t('x.slots')")).toEqual([]);
    for (const id of ['slots', 'slots.', 'a.b!', '1a.b']) expect(findings({ [id]: line('x') }, `t('${id}')`)).toEqual([`red ${C} ${id} | a line id is dotted lower-case words, like "slots.empty.body"`]);
    expect(findings({ 'slots.empty.body': { text: 'x' }, 'slots.b.c': { where: 'x' }, 'slots.c.d': 'x' }, "t('slots.empty.body'); t('slots.b.c'); t('slots.c.d')")).toEqual([
      `red ${C} slots.empty.body | a line needs its "text" and "where" it is said`,
      `red ${C} slots.b.c | a line needs its "text" and "where" it is said`,
      `red ${C} slots.c.d | a line needs its "text" and "where" it is said`,
    ]);
    expect(findings({ 'slots.empty.body': line('x', { status: 'final' }) })).toEqual([`red ${C} slots.empty.body | a line's status is placeholder or owner`]);
    expect(findings({ 'slots.empty.body': line('Hi {first name} {} {2x} {ok2}') })).toEqual([
      `red ${C} slots.empty.body | "{first name}" is not a well-formed slot for a value`,
      `red ${C} slots.empty.body | "{}" is not a well-formed slot for a value`,
      `red ${C} slots.empty.body | "{2x}" is not a well-formed slot for a value`,
    ]);
  });
  it('holds placeholder wording as unfinished only from the voice layer on', () => {
    const c = { 'slots.empty.body': line('x') };
    expect(findings(c, undefined, VOICE_LAYER - 1)).toEqual([]);
    expect(findings(c, undefined, VOICE_LAYER)).toEqual(['incomplete - | 1 lines still carry placeholder wording']);
    expect(findings({ 'slots.empty.body': line('x', { status: 'owner' }) }, undefined, VOICE_LAYER)).toEqual([]);
  });
  it('fails a malformed catalog, and says the catalog holds nothing', () => {
    const r = checkText(repo('[]'), 1);
    expect(all(r.result)).toEqual([`red ${C} | the catalog is not an object`]);
    expect(r.ids).toEqual(new Set());
    expect(all(checkText(repo('{ x'), 1).result)[0]).toMatch(/^red src\/core\/text\/catalog\.json \| src\/core\/text\/catalog\.json is not valid JSON/);
  });
  it('fails a malformed voice registry, holding the catalog all the same', () => {
    const v = (value: unknown) => all(checkText(fixture({ [V]: value, [C]: { 'slots.a.b': line('a slot') }, 'src/x/y.ts': "t('slots.a.b')" }).repo, 1).result);
    expect(v({ banned: [] })).toEqual([`red ${V} | the voice rules need a "source" and a "banned" list`]);
    expect(v({ source: 'x', banned: {} })).toEqual([`red ${V} | the voice rules need a "source" and a "banned" list`]);
    expect(v([])).toEqual([`red ${V} | the voice rules need a "source" and a "banned" list`]);
    expect(v('null')).toEqual([`red ${V} | the voice rules need a "source" and a "banned" list`]);
    expect(v({ source: 'x', banned: [{ pattern: '' , why: 'w' }, { pattern: 'p' }, 'x', { pattern: '(', why: 'x' }] })).toEqual([
      `red ${V} banned 0 | a banned pattern needs "pattern" and "why"`,
      `red ${V} banned 1 | a banned pattern needs "pattern" and "why"`,
      `red ${V} banned 2 | a banned pattern needs "pattern" and "why"`,
      `red ${V} banned 3 | the pattern doesn't compile: Invalid regular expression: /(/iu: Unterminated group`,
    ]);
    expect(all(checkText(fixture({ [C]: { 'slots.a.b': line('a slot') }, 'src/x/y.ts': "t('slots.a.b')" }).repo, 1).result)).toEqual([`red ${V} | ${V} is missing`]);
  });
  it('escapes a pipe in the inventory table', () => {
    const r = checkText(repo({ 'slots.empty.body': line('a | b', { where: 'x | y' }) }), 1);
    expect(r.result.generated[0]?.content).toContain('| x \\| y | `slots.empty.body` | a \\| b | placeholder |');
  });
});
