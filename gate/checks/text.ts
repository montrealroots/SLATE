import { PATHS } from '../lib/paths.ts';
import { isNonEmptyString, isRecord, isSourceFile, readJson, type Repo } from '../lib/repo.ts';
import { result, type CheckResult } from '../lib/types.ts';

/**
 * The text inventory (BUILD-ORDER layer 0): every line the game says lives in one catalog with an id, where it's
 * said and whose wording it is. A line nothing says is decoration (MANDATE rule 2); a line using the engine's
 * vocabulary breaks the voice (KEEP entry 2). The inventory the owner rewrites from is generated from the catalog.
 */
export const STATUSES = ['placeholder', 'owner'] as const;
/** From layer 6 (the voice) on, a placeholder line is unfinished work. */
export const VOICE_LAYER = 6;

const ID = /^[a-z][a-z0-9-]*(\.[a-z0-9-]+)+$/;
const PARAM = /\{([^}]*)\}/g;
/** The words between the slots for values: the engine's vocabulary is looked for there, not in a slot's name. */
const words = (text: string) => text.split(/\{[^}]*\}/);

interface Banned {
  pattern: RegExp;
  why: string;
}

function loadVoice(repo: Repo, r: ReturnType<typeof result>): Banned[] {
  const raw = readJson(repo, PATHS.voice);
  const voice = raw.ok && isRecord(raw.value) && isNonEmptyString(raw.value['source']) ? raw.value['banned'] : undefined;
  const out: Banned[] = [];
  if (!Array.isArray(voice)) {
    r.red(raw.ok ? 'the voice rules need a "source" and a "banned" list' : raw.why, PATHS.voice);
    return out;
  }
  for (const [i, b] of voice.entries()) {
    if (!isRecord(b) || !isNonEmptyString(b['pattern']) || !isNonEmptyString(b['why'])) {
      r.red('a banned pattern needs "pattern" and "why"', `${PATHS.voice} banned ${i}`);
      continue;
    }
    try {
      out.push({ pattern: new RegExp(b['pattern'], 'iu'), why: b['why'] });
    } catch (e) {
      r.red(`the pattern doesn't compile: ${(e as Error).message}`, `${PATHS.voice} banned ${i}`);
    }
  }
  return out;
}

export function checkText(repo: Repo, currentLayer: number): { result: CheckResult; ids: ReadonlySet<string> | undefined } {
  const r = result('text-inventory');
  const banned = loadVoice(repo, r);
  if (!repo.exists(PATHS.catalog)) {
    r.note('no text catalog yet: the first player-facing line arrives with layer 1');
    return { result: r, ids: undefined };
  }
  const raw = readJson(repo, PATHS.catalog);
  if (!raw.ok || !isRecord(raw.value)) {
    r.red(raw.ok ? 'the catalog is not an object' : raw.why, PATHS.catalog);
    return { result: r, ids: new Set<string>() };
  }
  const catalog = raw.value;
  const ids = new Set(Object.keys(catalog));

  // Where each id is said: a quoted literal of it in the app's source, outside the catalog.
  // Stryker disable next-line StringLiteral: every file listed was just found, so it reads.
  const sources = repo.files(PATHS.src).filter(isSourceFile).map((f) => repo.read(f) ?? '');
  const said = (id: string) => {
    const quoted = new RegExp(`(['"\`])${id.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}\\1`);
    return sources.some((s) => quoted.test(s));
  };

  const rows: string[] = [];
  let placeholders = 0;
  for (const [id, entry] of Object.entries(catalog)) {
    const at = `${PATHS.catalog} ${id}`;
    if (!ID.test(id)) r.red('a line id is dotted lower-case words, like "slots.empty.body"', at);
    if (!isRecord(entry) || !isNonEmptyString(entry['text']) || !isNonEmptyString(entry['where'])) {
      r.red('a line needs its "text" and "where" it is said', at);
      continue;
    }
    const status = entry['status'];
    if (!STATUSES.includes(status as (typeof STATUSES)[number])) r.red(`a line's status is ${STATUSES.join(' or ')}`, at);
    if (status === 'placeholder') placeholders += 1;
    const text = entry['text'];
    for (const [slot, name] of text.matchAll(PARAM)) {
      if (!/^[a-zA-Z][a-zA-Z0-9]*$/.test(String(name))) r.red(`"${slot}" is not a well-formed slot for a value`, at);
    }
    for (const b of banned) {
      if (words(text).some((w) => b.pattern.test(w))) r.red(`the line uses the engine's vocabulary (${b.why}): "${text}"`, at);
    }
    if (!said(id)) r.red('nothing in the game says this line', at);
    rows.push(`| ${String(entry['where']).replace(/\|/g, '\\|')} | \`${id}\` | ${text.replace(/\|/g, '\\|')} | ${String(status)} |`);
  }
  if (currentLayer >= VOICE_LAYER && placeholders > 0) r.incomplete(`${placeholders} lines still carry placeholder wording`);

  r.generate(
    `${PATHS.matrixDir}/TEXT.md`,
    [
      '# Every Line The Game Says',
      '',
      'Generated by the gate from `src/core/text/catalog.json`; do not edit by hand. Placeholder lines are the',
      "builder's draft in the voice standard (KEEP entry 2); the owner's wording replaces them.",
      '',
      `Lines: ${ids.size} (${placeholders} placeholder, ${ids.size - placeholders} the owner's).`,
      '',
      '| Where | Id | Text | Wording |',
      '|---|---|---|---|',
      ...rows,
      '',
    ].join('\n'),
  );
  r.note(`${ids.size} lines in the catalog, ${placeholders} placeholder`);
  return { result: r, ids };
}
